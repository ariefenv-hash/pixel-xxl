#!/usr/bin/env python3
"""v1.05 资产合并包构建（分片版）：assets/ 全部素材按序拼接为若干 ≤16MB 的内容寻址分片，
分片清单（文件名→[分片号,片内offset,长度]）写回 lib/project-loader.js 的 BEGIN/END PACK 标记区。

设计要点（详见 docs/PORTING.md §9）：
- 拆片原因：jsDelivr GH 源单文件上限 20MB（实测 403: "File size exceeded the configured
  limit of 20 MB."），≤16MB 分片可上 CDN；两片可并行下载，弱网吞吐再提速；
- 分片名 = pack-<sha256[:8]>-pN.bin：内容寻址 ⇒ 不可变，SW cache-first 跨版本不串档；
- 资产内容变更后重跑本脚本即可（旧分片删除、新分片落盘、标记区同步重写）。
"""
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'assets')
LOADER = os.path.join(ROOT, 'lib', 'project-loader.js')
SPLIT = 16_000_000  # < jsDelivr 20MB 上限，留余量

BEGIN = '  // BEGIN PACK — auto-generated by scripts/build-pack.py; content-addressed, do not edit'
END = '  // END PACK'


def main():
    files = sorted(
        f for f in os.listdir(ASSETS)
        if not f.startswith('pack-') and os.path.isfile(os.path.join(ASSETS, f))
    )
    h = hashlib.sha256()
    for name in files:
        h.update(open(os.path.join(ASSETS, name), 'rb').read())
    sha8 = h.hexdigest()[:8]

    # 切片：贪心装填，超 SPLIT 开新片
    parts_blobs = []   # list[bytearray]
    parts_meta = []    # list[{name, size, offset}] offset=该片在全量字节流中的起始
    index = {}         # name -> [partIdx, offsetInPart, size]
    cur, cur_size, stream_off = [], 0, 0
    for name in files:
        data = open(os.path.join(ASSETS, name), 'rb').read()
        if cur and cur_size + len(data) > SPLIT:
            parts_blobs.append(b''.join(cur))
            parts_meta.append({'size': cur_size, 'offset': stream_off})
            stream_off += cur_size
            cur, cur_size = [], 0
        index[name] = [len(parts_blobs), cur_size, len(data)]
        cur.append(data)
        cur_size += len(data)
    if cur:
        parts_blobs.append(b''.join(cur))
        parts_meta.append({'size': cur_size, 'offset': stream_off})
        stream_off += cur_size

    names = [f'pack-{sha8}-p{i + 1}.bin' for i in range(len(parts_blobs))]
    for name, blob in zip(names, parts_blobs):
        open(os.path.join(ASSETS, name), 'wb').write(blob)

    # 清理旧分片
    removed = []
    for f in os.listdir(ASSETS):
        if f.startswith('pack-') and f not in names:
            os.remove(os.path.join(ASSETS, f))
            removed.append(f)

    # project.json 引用面核对（md5ext 与 assetId+dataFormat 两种引用口径都要在包内）
    proj = json.load(open(os.path.join(ROOT, 'project.json')))
    refs = set()
    for t in proj.get('targets', []):
        for kind in ('costumes', 'sounds'):
            for a in t.get(kind, []):
                refs.add(a.get('md5ext') or (a.get('assetId') + '.' + a.get('dataFormat')))
    missing = sorted(r for r in refs if r is not None and r not in index)

    # 写回标记区
    src = open(LOADER, encoding='utf-8').read()
    lines = [BEGIN, '  const PACK = {', f"    repo: 'ariefenv-hash/pixel-xxl',", "    branch: 'main',",
             '    parts: [']
    for name, meta in zip(names, parts_meta):
        lines.append(f"      {{ name: '{name}', size: {meta['size']}, offset: {meta['offset']} }},")
    lines.append('    ],')
    lines.append(f'    size: {stream_off},')
    lines.append('    files: {')
    for name in files:
        p, off, size = index[name]
        lines.append(f"      '{name}': [{p}, {off}, {size}],")
    lines += ['    }', '  };', END]
    block = '\n'.join(lines) + '\n'
    pat = re.compile(re.escape(BEGIN) + r'\n.*?\n' + re.escape(END) + '\n', re.S)
    if not pat.search(src):
        print('ERROR: PACK markers not found in project-loader.js')
        sys.exit(1)
    open(LOADER, 'w', encoding='utf-8').write(pat.sub(lambda _: block, src, count=1))

    print(f'pack stem: pack-{sha8}  parts: {len(names)}  sizes: {[m["size"] for m in parts_meta]}  total: {stream_off}')
    print(f'project refs: {len(refs)}  missing-in-pack: {missing if missing else 0}')
    print(f'old packs removed: {removed if removed else 0}')
    if missing:
        sys.exit(2)


if __name__ == '__main__':
    main()
