#!/usr/bin/env python3
"""v1.04 资产合并包构建：assets/ 全部素材按序拼接为单个内容寻址包，
并把包清单（文件名→[offset,size]）写回 lib/project-loader.js 的 BEGIN/END PACK 标记区。

设计要点（详见 docs/PORTING.md §8）：
- 包名 = pack-<sha256[:8]>.bin：内容寻址 ⇒ 不可变，SW cache-first 跨版本不串档；
- 资产内容变更后重跑本脚本即可（旧包删除，新包落盘，标记区同步重写）；
- project.json 引用面/磁盘孤儿面均被包覆盖（含时钟指针等仅以 assetId 引用的文件）。
"""
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'assets')
LOADER = os.path.join(ROOT, 'lib', 'project-loader.js')

BEGIN = '  // BEGIN PACK — auto-generated by scripts/build-pack.py; content-addressed, do not edit'
END = '  // END PACK'


def main():
    files = sorted(
        f for f in os.listdir(ASSETS)
        if not f.startswith('pack-') and os.path.isfile(os.path.join(ASSETS, f))
    )
    h = hashlib.sha256()
    blobs = []
    index = {}
    offset = 0
    for name in files:
        data = open(os.path.join(ASSETS, name), 'rb').read()
        h.update(data)
        blobs.append(data)
        index[name] = [offset, len(data)]
        offset += len(data)
    sha8 = h.hexdigest()[:8]
    pack_name = f'pack-{sha8}.bin'
    pack_path = os.path.join(ASSETS, pack_name)
    with open(pack_path, 'wb') as fp:
        for data in blobs:
            fp.write(data)

    # 清理旧包
    removed = []
    for f in os.listdir(ASSETS):
        if f.startswith('pack-') and f != pack_name:
            os.remove(os.path.join(ASSETS, f))
            removed.append(f)

    # project.json 引用面核对（md5ext 或 assetId+dataFormat 两种引用方式都要在包内）
    proj = json.load(open(os.path.join(ROOT, 'project.json')))
    refs = set()
    for t in proj.get('targets', []):
        for c in t.get('costumes', []):
            refs.add(c.get('md5ext') or (c.get('assetId') + '.' + c.get('dataFormat')))
        for s in t.get('sounds', []):
            refs.add(s.get('md5ext') or (s.get('assetId') + '.' + s.get('dataFormat')))
    missing = sorted(r for r in refs if r not in index and r is not None)

    # 写回标记区
    src = open(LOADER, encoding='utf-8').read()
    lines = [BEGIN, '  const PACK = {', f"    name: '{pack_name}',", f'    size: {offset},', '    files: {']
    for name in files:
        off, size = index[name]
        lines.append(f"      '{name}': [{off}, {size}],")
    lines += ['    }', '  };', END]
    block = '\n'.join(lines) + '\n'
    pat = re.compile(re.escape(BEGIN) + r'\n.*?\n' + re.escape(END) + '\n', re.S)
    if not pat.search(src):
        print('ERROR: PACK markers not found in project-loader.js')
        sys.exit(1)
    open(LOADER, 'w', encoding='utf-8').write(pat.sub(lambda _: block, src, count=1))

    print(f'pack: {pack_name}  bytes: {offset}  files: {len(files)}')
    print(f'project refs: {len(refs)}  missing-in-pack: {missing if missing else 0}')
    print(f'old packs removed: {removed if removed else 0}')
    if missing:
        sys.exit(2)


if __name__ == '__main__':
    main()
